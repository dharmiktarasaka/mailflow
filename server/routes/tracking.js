import express from 'express'
import { Draft, LeadEvent as Event } from '../db/models.js'

const router = express.Router()

// Serve 1x1 tracking pixel
router.get('/:draft_id.png', async (req, res) => {
  try {
    const { draft_id } = req.params

    // Log open event
    const draft = await Draft.findById(draft_id).lean()
    if (draft) {
      const event = new Event({
        lead_id: draft.lead_id,
        draft_id: draft._id,
        event_type: 'opened',
        metadata: JSON.stringify({ 
          timestamp: new Date().toISOString(), 
          user_agent: req.get('user-agent') 
        })
      })
      await event.save()
    }

    // Return 1x1 transparent PNG
    res.setHeader('Content-Type', 'image/png')
    res.setHeader('Cache-Control', 'no-cache, no-store, must-revalidate')
    res.setHeader('Pragma', 'no-cache')
    res.setHeader('Expires', '0')

    // 1x1 transparent PNG (base64)
    const transparentPng = Buffer.from([
      0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44,
      0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f,
      0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x0a, 0x49, 0x44, 0x41, 0x54, 0x08, 0xd7, 0x63, 0x00,
      0x00, 0x00, 0x02, 0x00, 0x01, 0xe2, 0x21, 0xbc, 0x33, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45,
      0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
    ])

    res.send(transparentPng)
  } catch (error) {
    console.error('Tracking pixel error:', error)
    // Still return pixel on error
    const transparentPng = Buffer.from([
      0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44,
      0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f,
      0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x0a, 0x49, 0x44, 0x41, 0x54, 0x08, 0xd7, 0x63, 0x00,
      0x00, 0x00, 0x02, 0x00, 0x01, 0xe2, 0x21, 0xbc, 0x33, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45,
      0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
    ])
    res.setHeader('Content-Type', 'image/png')
    res.send(transparentPng)
  }
})

export default router

